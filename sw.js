function broadcast(message) {
    self.clients.matchAll({ includeUncontrolled: true }).then(clients => {
        for (const client of clients) {
            try { client.postMessage(message); } catch (e) { /* client went away */ }
        }
    }).catch(() => { /* no clients */ });
}

self.addEventListener('install', event => {
    event.waitUntil((async () => {
        // The shell must be reachable offline, so an installed app can always
        // reload into the bootstrap.
        try {
            const cache = await caches.open(CACHE_NAME);
            await Promise.all(SHELL_FILES.map(url =>
                cache.add(url).catch(() => { /* keep going: the OS lives in OPFS */ })
            ));
        } catch (e) { /* caches unavailable */ }

        // Install the OS core into OPFS. A failure here (offline first run)
        // must not abort the whole installation: the page retries through the
        // 'ensure-core' message and reports the problem to the user.
        try {
            await ensureCore();
        } catch (e) {
            corePromise = null;
        }

        // Take over immediately on a first install (there is no previous
        // worker to keep the page on). On an update we stay in "waiting" so
        // the running session is not swapped out from under the user.
        if (!self.registration.active) await self.skipWaiting();
    })());
});

self.addEventListener('activate', event => {
    event.waitUntil((async () => {
        const names = await caches.keys();
        await Promise.all(names.filter(name => name !== CACHE_NAME).map(name => caches.delete(name)));
        await self.clients.claim();
    })());
});

self.addEventListener('message', event => {
    const data = event.data || {};
    const reply = (message) => {
        try { event.source && event.source.postMessage(message); } catch (e) { /* no source */ }
    };

    if (data.type === 'ensure-core') {
        event.waitUntil((async () => {
            try {
                const info = await ensureCore();
                reply({ type: 'ensure-core', __id: data.__id, ok: true, version: info.version, installedAt: info.installedAt, files: info.files });
            } catch (e) {
                reply({ type: 'ensure-core', __id: data.__id, ok: false, error: String((e && e.message) || e) });
            }
        })());
        return;
    }

    if (data.type === 'core-status') {
        event.waitUntil((async () => {
            try {
                const info = await coreInstalled();
                reply({
                    type: 'core-status',
                    __id: data.__id,
                    ok: !!info,
                    version: info ? info.version : CORE_VERSION,
                    installedAt: info ? info.installedAt : 0,
                    files: info ? info.files : 0
                });
            } catch (e) {
                reply({ type: 'core-status', __id: data.__id, ok: false, error: String((e && e.message) || e) });
            }
        })());
        return;
    }

    if (data.type === 'pending-update') {
        // The update service keeps a downloaded update in the virtual
        // filesystem until the machine restarts. The bootstrap asks for it
        // before the shell loads, so it can show the update screen.
        event.waitUntil((async () => {
            try {
                const tree = await readTree();
                const node = tree
                    ? resolveNode(tree, ['system', 'programs data', 'updates', 'pending.json'])
                    : null;
                let pending = null;
                if (node && node.type === 'file' && node.content) {
                    try { pending = JSON.parse(node.content); } catch (e) { pending = null; }
                }
                reply({ type: 'pending-update', __id: data.__id, ok: true, pending });
            } catch (e) {
                reply({ type: 'pending-update', __id: data.__id, ok: false, error: String((e && e.message) || e) });
            }
        })());
        return;
    }

    if (data.type === 'tree-changed') {
        // The shell changed the virtual filesystem: drop the cached snapshot
        // so the next request is answered from the new tree.
        treeCache = { at: 0, tree: null };
        return;
    }

    if (data.type === 'core-gc') {
        event.waitUntil(gcCoreVersions());
        return;
    }

    if (data.type === 'skip-waiting') {
        self.skipWaiting();
        return;
    }
});
