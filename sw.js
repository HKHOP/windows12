const CORE_PREFIXES = ['js/', 'css/', 'assets/'];
const CORE_FILES = ['shell.html', 'core-manifest.json'];

function scopeRelative(pathname) {
    return pathname.startsWith(SCOPE_PATH) ? pathname.slice(SCOPE_PATH.length) : pathname.replace(/^\//, '');
}

function isCorePath(rel) {
    if (CORE_FILES.includes(rel)) return true;
    return CORE_PREFIXES.some(prefix => rel.startsWith(prefix));
}

function notFound() {
    return new Response('Not found', { status: 404, headers: { 'Content-Type': 'text/plain' } });
}

function offline() {
    return new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain' } });
}

// Network-first with an offline cache fallback. Only the tiny shell is
// cached; the OS itself is answered from OPFS.
async function defaultFetch(req) {
    const cache = await caches.open(CACHE_NAME);
    try {
        const response = await fetch(req);
        if (response && response.ok) {
            cache.put(req, response.clone()).catch(() => { /* best effort */ });
        }
        return response;
    } catch (e) {
        const cached = await cache.match(req, { ignoreSearch: true });
        if (cached) return cached;
        throw e;
    }
}

// /js/â€¦, /css/â€¦, /assets/â€¦ , /shell.html, /core-manifest.json â†’ OPFS core
async function handleCoreRequest(req, url) {
    const rel = scopeRelative(url.pathname);
    const file = await readCoreFile(rel);
    if (!file) {
        // Not part of the core bundle â€” try the network (a dev server may
        // serve it) and fall back to a clean 404.
        try {
            const response = await fetch(req);
            if (response && response.ok) return response;
        } catch (e) { /* offline */ }
        return notFound();
    }

    // The worker is the authority on which core version is running, so the
    // manifest always reports this worker's version.
    if (rel === 'core-manifest.json') {
        try {
            const manifest = JSON.parse(await file.text());
            if (manifest && manifest.version !== CORE_VERSION) {
                manifest.version = CORE_VERSION;
                return new Response(JSON.stringify(manifest), {
                    headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }
                });
            }
        } catch (e) { /* fall through: serve the file as-is */ }
    }

    return new Response(file, {
        headers: {
            'Content-Type': mimeOf(rel),
            'Cache-Control': 'no-store'
        }
    });
}

// Finds the app folder a path belongs to: the nearest ancestor that carries
// a valid manifest.json. Returns null when the path is not inside an app.
async function appRootFor(tree, parts) {
    for (let i = parts.length; i > 0; i--) {
        const folder = parts.slice(0, i);
        const node = resolveNode(tree, folder);
        if (!node || node.type !== 'folder' || !node.children) continue;
        const manifestNode = node.children['manifest.json'];
        if (!manifestNode) continue;
        const manifest = parseManifestNode(manifestNode);
        if (!manifest) return null;

        // OS-only trees are never app code.
        if (folder[0] === 'system') return null;
        // Another profile's folders stay private.
        if (folder[0] === 'users') {
            const uid = await activeUser();
            if (!uid || folder[1] !== uid) return null;
        }
        return { folder, manifest };
    }
    return null;
}

function parseManifestNode(node) {
    if (!node || node.type !== 'file') return null;
    const raw = typeof node.content === 'string' ? node.content : null;
    if (!raw) return null;
    let manifest;
    try { manifest = JSON.parse(raw); } catch (e) { return null; }
    if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) return null;
    if (typeof manifest.id !== 'string' || !manifest.id) return null;
    if (typeof manifest.name !== 'string' || !manifest.name) return null;
    return manifest;
}

// /js/apps/<folder>/<restâ€¦> â†’ a file of an app folder in the virtual
// filesystem.
//
// An app IS a folder: the folder path is its handle and the URL shows it.
// The folder is ONE url segment (its separators are escaped), so an app
// always sits at the same depth:
//
//   /js/apps/Program%20Files%2Fnotepad/main.js   an app in the filesystem
//
// Only files that live inside a valid app folder are served from the
// virtual filesystem, so this route can never be used to read arbitrary
// user files. Everything else (the app catalog, the icons of apps that are
// not installed) comes from the network.
async function handleAppRequest(req, url) {
    const rel = url.pathname.slice(APPS_PREFIX.length);
    const raw = rel.split('/').filter(Boolean);
    if (!raw.length) return defaultFetch(req);

    // The first segment may be an encoded folder path
    // ('Program%20Files%2Fnotepad').
    let treePath = [];
    for (const seg of raw) {
        let decoded;
        try { decoded = decodeURIComponent(seg); } catch { return defaultFetch(req); }
        if (!decoded || decoded === '.' || decoded === '..' || decoded.includes('\0')) return defaultFetch(req);
        treePath.push(...decoded.split('/'));
    }
    if (treePath.some(p => p === '.' || p === '..' || p.includes('\\'))) return defaultFetch(req);

    // 1. The virtual filesystem: an app's own files.
    let tree = null;
    try { tree = await readTree(); } catch (e) { tree = null; }
    if (tree) {
        const root = await appRootFor(tree, treePath);
        if (root) {
            const node = resolveNode(tree, treePath);
            if (node && node.type === 'file') return serveNode(node);
        }
    }

    // 2. The OS core (the builtin apps ship inside it).
    const coreFile = await readCoreFile('js/apps/' + raw.join('/'));
    if (coreFile) {
        return new Response(coreFile, {
            headers: {
                'Content-Type': mimeOf(raw[raw.length - 1]),
                'Cache-Control': 'no-store'
            }
        });
    }

    // 3. The app catalog is not part of the core (an app update must not
    // ship a new OS), so it is fetched from the network like any other.
    return defaultFetch(req);
}

self.addEventListener('fetch', event => {
    const req = event.request;
    if (req.method !== 'GET') return;

    let url;
    try { url = new URL(req.url); } catch { return; }
    if (url.protocol !== 'http:' && url.protocol !== 'https:') return; // blob:, data:, extensionâ€¦
    if (url.origin !== self.location.origin) return; // cross-origin: browser default

    if (url.pathname === REGISTRY_PATH) {
        event.respondWith(defaultFetch(req));
        return;
    }

    if (url.pathname.startsWith(APPS_PREFIX)) {
        event.respondWith(handleAppRequest(req, url));
        return;
    }

    if (isCorePath(scopeRelative(url.pathname))) {
        event.respondWith(handleCoreRequest(req, url));
        return;
    }

    event.respondWith(defaultFetch(req));
});

