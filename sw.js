// Windows 12 service worker â€” the OS file server.
//
// The operating system no longer lives on the web server. Everything the OS
// needs at runtime (stylesheets, ES modules, the SDK, the builtin apps, the
// sounds) is shipped as one bundle (w12-core.pkg), downloaded once, unpacked
// into the Origin Private File System (OPFS) and served from there.
//
// This worker has four jobs:
//
//   1. Core installer: download w12-core.pkg, unpack it into
//      w12/core/<version>/â€¦ and record the active version in
//      w12/core/current.json.
//   2. Core host: serve /js/â€¦, /css/â€¦, /assets/â€¦, /shell.html and
//      /core-manifest.json out of OPFS, so ES module imports resolve against
//      the canonical site URLs and the whole OS boots with no network.
//   3. Virtual package host: serve /js/apps/<id>/â€¦ for INSTALLED store apps
//      straight out of the virtual filesystem, so store apps run from disk.
//   4. Offline shell: keep the tiny bootstrap (index.html, manifest.json,
//      favicon.svg) in a cache so an offline reload still reaches the OS.
//
// Nothing here is a "cache" of the OS any more: the OPFS copy is the single
// source of truth and is always answered with `no-store` so the browser
// never keeps a second, stale copy.
//
// Only genuinely-online features are affected by being offline: cross-origin
// fetches (Weather, Copilot, peer pairing), remote iframes (Browser) and the
// Store's package downloads.
//
// The core metadata and the app distribution map below are GENERATED by
// build-core.js and build-registry.js â€” do not hand-edit those blocks.

