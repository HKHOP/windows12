let rootPromise = null;
function opfsRoot() {
    if (!rootPromise) rootPromise = navigator.storage.getDirectory();
    return rootPromise;
}

async function opfsDir(parts, create) {
    let dir = await opfsRoot();
    for (const part of parts) {
        dir = await dir.getDirectoryHandle(part, { create: !!create });
    }
    return dir;
}

async function opfsGetFile(parts) {
    try {
        let dir = await opfsRoot();
        for (let i = 0; i < parts.length - 1; i++) {
            dir = await dir.getDirectoryHandle(parts[i]);
        }
        const handle = await dir.getFileHandle(parts[parts.length - 1]);
        return await handle.getFile();
    } catch (e) {
        return null;
    }
}

// Writes bytes into OPFS. Uses a sync access handle when the browser allows
// it (fastest, and the only option on older Safari), otherwise falls back to
// the async writable stream.
async function opfsWriteFile(parts, data) {
    const bytes = data instanceof Uint8Array ? data : new Uint8Array(data);
    const dir = await opfsDir(parts.slice(0, -1), true);
    const handle = await dir.getFileHandle(parts[parts.length - 1], { create: true });

    try {
        const access = await handle.createSyncAccessHandle();
        try {
            access.truncate(0);
            access.write(bytes, { at: 0 });
            access.flush();
        } finally {
            access.close();
        }
        return true;
    } catch (e) {
        // createSyncAccessHandle is unavailable here â€” use the writable stream.
    }

    try {
        const writable = await handle.createWritable();
        await writable.write(bytes);
        await writable.close();
        return true;
    } catch (e) {
        return false;
    }
}

async function opfsRemove(parts, recursive) {
    try {
        const dir = await opfsDir(parts.slice(0, -1), false);
        await dir.removeEntry(parts[parts.length - 1], { recursive: !!recursive });
        return true;
    } catch (e) {
        return false;
    }
}

async function opfsListDir(parts) {
    const names = [];
    try {
        const dir = await opfsDir(parts, false);
        for await (const name of dir.keys()) names.push(name);
    } catch (e) { /* missing directory */ }
    return names;
}

