let corePromise = null;

function coreRootParts() {
    return splitPath(CORE_DIR + '/' + CORE_VERSION);
}

// The bundle is installed under a version directory, so a service worker
// always serves exactly the core it was built with â€” an update never mixes
// old and new files in one running session.
//
// The "is my core installed?" test looks ONLY at this worker's own version
// directory. A shared pointer would be wrong: while a new worker waits to
// take over, it installs its own core, and the old worker must not mistake
// that for its own core being replaced.
async function coreInstalled() {
    const file = await opfsGetFile([...coreRootParts(), 'core-info.json']);
    if (!file) return null;
    try {
        const info = JSON.parse(await file.text());
        if (!info || info.version !== CORE_VERSION) return null;
        // The version directory must actually hold the bundle.
        const probe = await opfsGetFile([...coreRootParts(), 'core-manifest.json']);
        if (!probe) return null;
        return info;
    } catch (e) {
        return null;
    }
}

// Makes sure this worker's core is on disk. The check is done every time:
// the storage can be wiped underneath the worker (a reset, a quota purge),
// and then the core has to be installed again.
async function ensureCore() {
    if (corePromise) {
        try { return await corePromise; } catch (e) { corePromise = null; }
    }
    const existing = await coreInstalled();
    if (existing) return existing;
    corePromise = installCore();
    try {
        return await corePromise;
    } finally {
        corePromise = null;
    }
}

async function installCore() {
    const response = await fetch(new URL(CORE_PACKAGE, self.registration.scope).href, { cache: 'no-store' });
    if (!response.ok) throw new Error('core-download-failed:' + response.status);

    const buffer = new Uint8Array(await response.arrayBuffer());
    const entries = await unzip(buffer);
    const parts = coreRootParts();

    let done = 0;
    for (const entry of entries) {
        if (!entry.name || entry.name.endsWith('/')) continue;
        const target = [...parts, ...splitPath(entry.name)];
        const ok = await opfsWriteFile(target, entry.data);
        if (!ok) throw new Error('core-write-failed:' + entry.name);
        done++;
        if (done % 25 === 0 || done === entries.length) {
            broadcast({ type: 'core-progress', done, total: entries.length });
        }
    }

    const info = {
        version: CORE_VERSION,
        hash: CORE_HASH,
        files: done,
        bytes: CORE_BYTES,
        installedAt: Date.now()
    };
    // The marker lives inside this version's own directory, so a worker
    // never confuses another version's install with its own.
    await opfsWriteFile([...parts, 'core-info.json'],
        new TextEncoder().encode(JSON.stringify(info)));
    broadcast({ type: 'core-installed', version: CORE_VERSION, files: done });
    return info;
}

// Removes core directories that are not the active version. Called by the
// page once it has booted the current core, so a running session is never
// pulled out from under itself. Versions the virtual filesystem still points
// at are kept as well â€” the \Windows mirror references them by name.
async function gcCoreVersions() {
    // A newer system is on its way. Its core belongs to the worker that is
    // installing or waiting for it, and that worker owns a different
    // version directory: deleting it would break that install (the worker
    // would unpack half a core and fail), and the update would never
    // arrive.
    const reg = self.registration;
    if (reg && (reg.waiting || reg.installing)) return;

    const names = await opfsListDir(splitPath(CORE_DIR));
    const keep = new Set([CORE_VERSION]);
    try {
        const tree = await readTree();
        if (tree) collectCoreVersions(tree, keep);
    } catch (e) { /* keep everything we cannot verify */ }
    for (const name of names) {
        if (keep.has(name)) continue;
        await opfsRemove(splitPath(CORE_DIR + '/' + name), true);
    }
}

// Walks the tree for 'core/<version>/â€¦' blob references and remembers the
// versions still in use.
function collectCoreVersions(node, keep) {
    if (!node) return;
    if (node.blobRef && node.blobRef.startsWith('core/')) {
        const version = node.blobRef.split('/')[1];
        if (version) keep.add(version);
    }
    if (node.type === 'folder' && node.children) {
        for (const child of Object.values(node.children)) collectCoreVersions(child, keep);
    }
}

async function readCoreFile(rel) {
    const file = await opfsGetFile([...coreRootParts(), ...splitPath(rel)]);
    return file;
}

// ---------------------------------------------------------------------------
// Minimal ZIP reader (stored + deflate)
// ---------------------------------------------------------------------------

const SIG_EOCD = 0x06054b50;
const SIG_CENTRAL = 0x02014b50;

async function inflateRaw(bytes) {
    if (typeof DecompressionStream === 'undefined') {
        throw new Error('core-unsupported-no-decompression');
    }
    const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
    return new Uint8Array(await new Response(stream).arrayBuffer());
}

async function unzip(bytes) {
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    const decoder = new TextDecoder('utf-8');

    let eocd = -1;
    const floor = Math.max(0, bytes.length - 22 - 65535);
    for (let i = bytes.length - 22; i >= floor; i--) {
        if (view.getUint32(i, true) === SIG_EOCD) { eocd = i; break; }
    }
    if (eocd < 0) throw new Error('core-bad-archive');

    const count = view.getUint16(eocd + 10, true);
    let offset = view.getUint32(eocd + 16, true);
    const out = [];

    for (let i = 0; i < count; i++) {
        if (view.getUint32(offset, true) !== SIG_CENTRAL) throw new Error('core-bad-archive');
        const method = view.getUint16(offset + 10, true);
        const compSize = view.getUint32(offset + 20, true);
        const nameLen = view.getUint16(offset + 28, true);
        const extraLen = view.getUint16(offset + 30, true);
        const commentLen = view.getUint16(offset + 32, true);
        const localOffset = view.getUint32(offset + 42, true);
        const name = decoder.decode(bytes.subarray(offset + 46, offset + 46 + nameLen));

        const localNameLen = view.getUint16(localOffset + 26, true);
        const localExtraLen = view.getUint16(localOffset + 28, true);
        const start = localOffset + 30 + localNameLen + localExtraLen;
        const raw = bytes.subarray(start, start + compSize);

        let data;
        if (method === 0) data = raw;
        else if (method === 8) data = await inflateRaw(raw);
        else throw new Error('core-bad-archive:method-' + method);

        out.push({ name, data });
        offset += 46 + nameLen + extraLen + commentLen;
    }
    return out;
}

// ---------------------------------------------------------------------------
// Virtual filesystem (tree snapshot straight from OPFS)
// ---------------------------------------------------------------------------

// The tree snapshot is re-read whenever it may have changed. OPFS
// File.lastModified is not a dependable change signal across browsers, so
// instead of trusting a timestamp we keep the parse for a very short window
// (coalescing a burst of asset requests for one app) and otherwise read
// fresh â€” an install must be visible immediately, without a reload.
let treeCache = { at: 0, tree: null };
const TREE_TTL_MS = 250;
async function readTree() {
    const now = Date.now();
    if (treeCache.tree && now - treeCache.at < TREE_TTL_MS) return treeCache.tree;
    const file = await opfsGetFile(splitPath('w12/fs.json'));
    if (!file) return null;
    let tree;
    try { tree = JSON.parse(await file.text()); } catch (e) { return null; }
    treeCache = { at: now, tree };
    return tree;
}

// Active user is needed to locate per-user packages. The file is tiny and
// only written on boot / install, so read it per app request.
async function activeUser() {
    try {
        const file = await opfsGetFile(splitPath('w12/session.json'));
        if (file) {
            const parsed = JSON.parse(await file.text());
            if (parsed && parsed.userId) return parsed.userId;
        }
    } catch (e) { /* fall through */ }
    return 'default';
}

function resolveNode(tree, parts) {
    let node = tree;
    for (const part of parts) {
        if (!node || node.type !== 'folder' || !node.children) return null;
        node = node.children[part];
    }
    return node || null;
}

// The app code is served from /fs/<folder>/â€¦ â€” the folder is the app's
// handle, and that is where it runs from. This route only carries the app
// catalog and the icons of apps that are not installed yet.

async function serveNode(node) {
    if (!node || node.type !== 'file') return null;

    const type = node.blobType || mimeOf(node.name);
    const headers = {
        'Content-Type': type,
        'Cache-Control': 'no-store'
    };

    if (node.blobRef) {
        let file = await opfsGetFile(splitPath(blobPath(node.blobRef)));
        if (!file) {
            // One retry: the OPFS worker may be mid-write (short-lived sync handle).
            await new Promise(r => setTimeout(r, 40));
            file = await opfsGetFile(splitPath(blobPath(node.blobRef)));
        }
        if (!file) return null;
        return new Response(file, { headers });
    }

    return new Response(node.content ?? '', { headers });
}

// Core files live under w12/core/<version>/â€¦, user files under w12/blobs/.
// The 'core/' prefix keeps the OS core out of the user's blob area.
function blobPath(ref) {
    if (String(ref).startsWith('core/')) return 'w12/' + ref;
    return 'w12/blobs/' + ref;
}

